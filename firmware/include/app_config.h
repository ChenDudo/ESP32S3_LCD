#pragma once

// 固件模式开关（改完重新编译即可，不需要改 platformio.ini）
//
//   1 = 点屏自检：只初始化屏 + 触摸，画测试图、扫 I2C、显示触摸坐标
//       适合：还没接 AHT20 / BMP280 / GPS，或还没焊上下拉电阻时先验证硬件
//   0 = 完整仪表盘：屏 + 触摸 + AHT20 / GY-BMP280 / ATGM336H
//
// 注意：两个模式下只有一份 setup()/loop() 参与编译，不会冲突。

#define APP_DISPLAY_TEST 1

// I2C 速率
//
//   100000  = 100kHz。没有外部 4.7K 上拉、用杜邦线连着调试时用这个档
//             （ESP32 内部上拉只有 45kΩ 量级，400kHz 下上升沿爬不起来，
//              表现就是扫描出一堆假地址、触摸完全无响应）
//   400000  = 400kHz。板上焊了 4.7K 上拉、走线短的时候用这个
#define APP_I2C_FREQ 100000

// 面板极性（改完重新编译）
//
//   LCD_INVERT   : 反显开关。表现是「白变黑、黑变白」时必须置 1。
//                  这块 3.5" IPS 屏实测需要反显（INVON），置 0 会出现
//                  白色页面显示成黑色、黑色页面显示成白色。
//   LCD_RGB_ORDER: 红蓝互换。表现是「红色显示成蓝色、黄色显示成青色」时置 1。
//                  注意：两个参数会互相影响，判断时以「白/黑是否正确」先定 INVERT，
//                  再看三原色对不对，最后定 RGB_ORDER。
#define LCD_INVERT    1
#define LCD_RGB_ORDER 0

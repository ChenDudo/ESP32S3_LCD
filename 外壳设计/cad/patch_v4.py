def apply(path, repls):
    s = io.open(path, encoding="utf-8").read()
    miss = []
    for old, new in repls:
        n = s.count(old)
        if n != 1:
            miss.append((n, old[:70]))
            continue
        s = s.replace(old, new, 1)
    io.open(path, "w", encoding="utf-8").write(s)
    print(f"{path}: {len(repls)-len(miss)}/{len(repls)} 替换成功")
    for n, o in miss:
        print(f"   !! 命中 {n} 次：{o}")
    return len(miss)


